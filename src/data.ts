// 単元: 「一つの花」 今西 祐行（いまにし すけゆき）
// 出典: 光村図書 小学校国語 4年（物語文）
// NOTE: 本文は教科書本文に忠実に転記。物語文のため、説明文向けの型を物語向けに再定義している。
// 重要: 各ページの本文は「\n」で場面（だん落）に区切り、structure の同ページの要素と
//        「同じ数・同じ順番」で1対1に対応させている（読むモード・場面ハイライトが依存）。

export type Page = {
  id: number;
  text: string;
  pageNumber: string;
  paragraphRange: string; // 例: "場面1"
};

export type Question = {
  id: number;
  pageId: number;
  type: 'extract' | 'choice' | 'free';
  question: string;
  targetText?: string; // 下線を引く位置。ぬき出し問題では使わず、選択問題で「下線部について問う」ときのみ使う。
  answer?: string[] | number;
  choices?: string[];
  sampleAnswer?: string;
  hint: string;   // ヒント①
  hint2?: string; // ヒント②（よりくわしい）
  charCount?: number; // 文字数指定ぬき出し（指定時は厳密に一致）
};

export type Kanji = {
  char: string;
  reading: string;
  meaning: string;
  pageId: number;
  example?: string;
};

// 物語文の「場面」構成。section は時代・場面の区切りを表す。
//   war     = 戦争中（日常・出征の日）
//   parting = 別れ・一つの花（山場）
//   after   = 十年後（戦後）
export type Scene = {
  num: number;
  pageId: number;
  section: 'war' | 'parting' | 'after';
  role: string;     // この場面（だん落）のはたらき
  summary: string;  // あらすじ
  feeling?: {        // 登場人物の心情・読みのポイント
    who: 'yumi' | 'father' | 'mother' | 'theme';
    point: string;    // 心情・読みどころ
    deep: string;     // さらに深い読み（テスト頻出の問い）
  };
};

// 後方互換のため Paragraph 名でも参照できるようにする
export type Paragraph = Scene;

// 対比表のセル: 行（戦争中 / 十年後）× 列（くらし / コスモス）
export type ContrastChip = {
  id: number;
  text: string;
  correctCell: 'war-life' | 'war-cosmos' | 'after-life' | 'after-cosmos' | 'distractor';
};

