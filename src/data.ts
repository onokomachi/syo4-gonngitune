// 物語文の「場面」構成。section は物語の展開の区切りを表す。
//   mischief  = いたずら（うなぎ事件）
//   grief     = 兵十のかなしみ・ごんの後悔
//   atonement = つぐないの日々
//   irony     = すれちがい（神様のしわざだと思いこまれる）
//   tragedy   = 悲しい結末
export type Scene = {
  num: number;
  pageId: number;
  section: 'mischief' | 'grief' | 'atonement' | 'irony' | 'tragedy';
  role: string;     // この場面のはたらき
  summary: string;  // あらすじ
  feeling?: {        // 登場人物の心情・読みのポイント
    who: 'gon' | 'hyoju' | 'kasuke' | 'theme';
    point: string;    // 心情・読みどころ
    deep: string;     // さらに深い読み（テスト頻出の問い）
  };
};

// 後方互換のため Paragraph 名でも参照できるようにする
export type Paragraph = Scene;

